
import mongoose from "mongoose";

const activityEventSchema = new mongoose.Schema(
  {
    // Company reference
    organization: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Organization",
      required: true,
      index: true,
    },

    // Extension installation reference
    installation: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "BrowserInstallation",
      required: true,
      index: true,
    },

    // Employee reference
    employee: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // Unique event ID generated by extension
    eventId: {
      type: String,
      required: true,
      trim: true,
    },

    // Type of browser activity
    eventType: {
      type: String,
      enum: [
        "TAB_CREATED",
        "TAB_ACTIVATED",
        "TAB_UPDATED",
        "TAB_CLOSED",
        "WINDOW_FOCUSED",
        "WINDOW_BLURRED",
        "SYSTEM_IDLE",
        "SYSTEM_ACTIVE",
        "BROWSER_SESSION_STARTED",
        "BROWSER_SESSION_ENDED",
        "HEARTBEAT",
      ],
      required: true,
    },

    // Event timestamp
    timestamp: {
      type: Date,
      required: true,
    },

    // Sanitized event information
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
  },
  {
    timestamps: true,
    versionKey: false,
  }
);

// Prevent duplicate events from the same installation
activityEventSchema.index(
  { installation: 1, eventId: 1 },
  { unique: true }
);

// Organization-wise event history
activityEventSchema.index({
  organization: 1,
  timestamp: -1,
});

// Employee-wise event history
activityEventSchema.index({
  organization: 1,
  employee: 1,
  timestamp: -1,
});

const ActivityEvent = mongoose.model(
  "ActivityEvent",
  activityEventSchema
);

export default ActivityEvent;
